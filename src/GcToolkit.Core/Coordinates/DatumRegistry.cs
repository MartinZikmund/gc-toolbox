    private static readonly Dictionary<string, Datum> _byCode =
        All.GroupBy(d => Normalize(d.Code)).ToDictionary(g => g.Key, g => g.First());

    /// <summary>Finds a datum by code, ignoring case and hyphens (so <c>OGB-7</c> and <c>OGB7</c> match).</summary>
    public static Datum? Find(string? code)
        => code is not null && _byCode.TryGetValue(Normalize(code), out var d) ? d : null;

    private static string Normalize(string code) => code.Replace("-", string.Empty).ToUpperInvariant();
